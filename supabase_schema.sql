-- 1. สร้างตาราง Master Data ยาและเวชภัณฑ์ (medicine_master)
CREATE TABLE IF NOT EXISTS public.medicine_master (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR(255) NOT NULL UNIQUE,          -- BARCODE สินค้าผู้ต้องฯ (ใช้จับคู่)
    item_code VARCHAR(255) NOT NULL,               -- Code รหัสยา
    item_name TEXT NOT NULL,                       -- Name ชื่อยา
    medicine_type VARCHAR(255),                    -- MEDICINE TYPE ชนิดยา
    unit_name VARCHAR(100),                        -- Unit Name หน่วยนับ (TAB, BOT, CAP)
    image_url TEXT,                                -- รูปภาพ
    status VARCHAR(50) DEFAULT 'available',        -- สถานะ
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- สร้าง Index เพื่อให้ iPad ค้นหาด้วยบาร์โค้ดได้รวดเร็วระดับ millisecond
CREATE INDEX IF NOT EXISTS idx_medicine_master_barcode ON public.medicine_master (barcode);
CREATE INDEX IF NOT EXISTS idx_medicine_master_item_code ON public.medicine_master (item_code);

-- 2. สร้างตารางบันทึกประวัติการสแกน (scan_audit_logs)
CREATE TABLE IF NOT EXISTS public.scan_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scanned_code VARCHAR(255) NOT NULL,
    is_matched BOOLEAN DEFAULT FALSE,
    item_code VARCHAR(255),
    item_name TEXT,
    medicine_type VARCHAR(255),
    verified_by VARCHAR(100) DEFAULT 'iPad Station',
    scanned_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_scan_logs_scanned_at ON public.scan_audit_logs (scanned_at DESC);

-- 3. เปิดสิทธิ์ Row Level Security (RLS) แบบอ่าน/เขียนทั่วไปสำหรับระบบภายใน
ALTER TABLE public.medicine_master ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scan_audit_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access on medicine_master" 
ON public.medicine_master FOR SELECT USING (true);

CREATE POLICY "Allow public insert/update on medicine_master" 
ON public.medicine_master FOR ALL USING (true);

CREATE POLICY "Allow public access on scan_audit_logs" 
ON public.scan_audit_logs FOR ALL USING (true);
